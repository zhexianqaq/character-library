/** 作品 → 出处类型（除了 EVA 是动画，其余都是游戏） */
const CATEGORY = { EVA: '动画' };

export const ROSTER = Object.fromEntries(
  Object.entries(RAW).map(([work, text]) => [
    work,
    text
      .split(/[，,]/)
      .map((s) => s.trim())
      .filter(Boolean),
  ])
);

if (process.argv[1] && process.argv[1].endsWith('_seed-roster.mjs')) {
  const apply = process.argv.includes('--apply');
  const works = Object.keys(ROSTER);
  let bad = 0;
  let sum = 0;
  for (const w of works) {
    const n = ROSTER[w].length;
    sum += n;
    const ok = n === EXPECT[w];
    if (!ok) bad += 1;
    console.log(`${ok ? '✓' : '✗'} ${w.padEnd(12)} ${String(n).padStart(3)} / ${EXPECT[w]}${CATEGORY[w] ? ' · ' + CATEGORY[w] : ''}`);
  }
  console.log(`\n合计 ${works.length} 部作品 · ${sum} 条角色条目` + (bad ? ` · ${bad} 部数量不符` : ' · 数量全部对得上'));
  if (bad) process.exit(2);

  if (apply) {
    const BASE = 'http://127.0.0.1:7788';
    const j = async (u, o) => {
      const r = await fetch(BASE + u, o);
      const t = await r.text();
      let body = null;
      try { body = t ? JSON.parse(t) : null; } catch { body = t; }
      return { status: r.status, body };
    };
    const post = (u, d) => j(u, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(d || {}) });
    const patch = (u, d) => j(u, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(d || {}) });

    // 角色集
    const shelves = (await j('/api/overview')).body.shelves || [];
    const workShelf = shelves.find((s) => s.kind === 'work');
    if (!workShelf) throw new Error('没有角色集');
    console.log(`\n角色集 ${workShelf.id} · ${workShelf.name}（现有 ${workShelf.characterCount} 个条目）`);

    // 现有条目：名字 → {id, platforms, tags}
    const existing = new Map();
    const list = (await j(`/api/shelves/${workShelf.id}/characters?sort=name`)).body.items || [];
    for (const c of list) existing.set(c.name, { id: c.id, platforms: c.platforms || [], tags: c.tags || [] });

    // 1) 作品卡
    let resNew = 0;
    for (const w of works) {
      const r = await post('/api/resources/ensure', { name: w, category: CATEGORY[w] || '游戏' });
      if (r.body && r.body.created) resNew += 1;
    }
    console.log(`作品卡：新建 ${resNew} 张，其余已存在`);

    // 2) 角色
    let created = 0;
    let merged = 0;
    let fail = 0;
    const today = [];
    for (const w of works) {
      const cat = CATEGORY[w] || '游戏';
      for (const name of ROSTER[w]) {
        const hit = existing.get(name);
        if (hit) {
          const has = hit.platforms.some((p) => String(p.handle || '') === w);
          const tags = new Set(hit.tags);
          const needTag = !tags.has(w);
          if (!has || needTag) {
            const next = has ? hit.platforms : [...hit.platforms, { platform: cat, handle: w, url: '' }];
            const r = await patch(`/api/characters/${hit.id}`, {
              platforms: next,
              ...(needTag ? { tags: [...new Set([...tags, w])] } : {}),
            });
            if (r.status !== 200) { fail += 1; console.log('  合并失败', name, r.status, r.body); }
            else { hit.platforms = next; hit.tags = [...new Set([...tags, w])]; merged += 1; }
          }
          continue;
        }
        const r = await post('/api/characters', {
          shelfId: workShelf.id,
          name,
          platforms: [{ platform: cat, handle: w, url: '' }],
          tags: [w],
        });
        if (r.status !== 200) { fail += 1; console.log('  新建失败', name, r.status, r.body && r.body.error); continue; }
        // create 接口不写 platforms，补一次
        const p2 = await patch(`/api/characters/${r.body.id}`, { platforms: [{ platform: cat, handle: w, url: '' }] });
        if (p2.status !== 200) { fail += 1; console.log('  出处写入失败', name); continue; }
        existing.set(name, { id: r.body.id, platforms: [{ platform: cat, handle: w, url: '' }], tags: [w] });
        created += 1;
        today.push(`${w} · ${name}`);
        if ((created + merged) % 100 === 0) console.log(`  … 已处理 ${created + merged}`);
      }
    }
    console.log(`\n新建 ${created} 个，合并（同名补出处/标签）${merged} 个，失败 ${fail} 个`);
    const after = (await j('/api/overview')).body.shelves.find((s) => s.id === workShelf.id);
    console.log(`角色集现在 ${after.characterCount} 个条目 · ${after.mediaCount} 个素材`);
  } else {
    console.log('\n（dry-run，未写库。加 --apply 才真正写入）');
  }
}
